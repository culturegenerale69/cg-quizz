// ========================================
// MÉLANGER LES QUESTIONS
// ========================================

function shuffleArray(array) {

const shuffled = [...array];

for (let i = shuffled.length - 1; i > 0; i--) {

const j = Math.floor(Math.random() * (i + 1));

[shuffled[i], shuffled[j]] =
[shuffled[j], shuffled[i]];

}

return shuffled;

}


// ========================================
// DÉMARRER LE QUIZ
// ========================================

function startQuiz() {

clearInterval(timerInterval);
clearTimeout(nextQuestionTimeout);

questions = shuffleArray(questionBank)
.slice(0, TOTAL_QUESTIONS);

currentQuestion = 0;
score = 0;

totalElapsedSeconds = 0;

answered = false;
quizFinished = false;

quizStartTime = Date.now();

questionScreen.hidden = false;
resultScreen.hidden = true;

showQuestion();

}


// ========================================
// AFFICHER UNE QUESTION
// ========================================

function showQuestion() {

clearInterval(timerInterval);
clearTimeout(nextQuestionTimeout);

if (currentQuestion >= questions.length) {

finishQuiz();
return;

}

answered = false;

const current = questions[currentQuestion];

questionCounter.textContent =
`Question ${currentQuestion + 1}/${TOTAL_QUESTIONS}`;

progressBar.style.width =
`${(currentQuestion / TOTAL_QUESTIONS) * 100}%`;

progressTrack.setAttribute(
"aria-valuenow",
currentQuestion
);

questionText.textContent = current.question;

answersContainer.innerHTML = "";

feedback.textContent = "";
feedback.className = "feedback";

timeLeft = QUESTION_TIME;

timerDisplay.classList.remove("urgent");

timerDisplay.textContent = `⏱️ ${timeLeft} s`;

current.answers.forEach((answer, index) => {

const button = document.createElement("button");

button.type = "button";

button.className = "answer-button";

button.textContent = answer;

button.addEventListener("click", () => {

selectAnswer(index);

});

answersContainer.appendChild(button);

});

questionStartTime = Date.now();

startTimer();

}


// ========================================
// CHRONOMÈTRE DE 15 SECONDES
// ========================================

function startTimer() {

timerInterval = setInterval(() => {

const elapsed = Math.floor(
(Date.now() - questionStartTime) / 1000
);

timeLeft = Math.max(
0,
QUESTION_TIME - elapsed
);

timerDisplay.textContent =
`⏱️ ${timeLeft} s`;

if (timeLeft <= 5) {

timerDisplay.classList.add("urgent");

}

if (timeLeft <= 0) {

clearInterval(timerInterval);

if (!answered) {

handleTimeout();

}

}

}, 100);

}


// ========================================
// VERROUILLER LES RÉPONSES
// ========================================

function lockAnswers() {

const buttons =
answersContainer.querySelectorAll("button");

buttons.forEach(button => {

button.disabled = true;

});

}


// ========================================
// METTRE À JOUR LA PROGRESSION
// ========================================

function updateProgressAfterAnswer() {

const completed = currentQuestion + 1;

progressBar.style.width =
`${(completed / TOTAL_QUESTIONS) * 100}%`;

progressTrack.setAttribute(
"aria-valuenow",
completed
);

}


// ========================================
// AFFICHER LA CORRECTION
// ========================================

function showCorrection(selectedIndex, timedOut = false) {

if (answered || quizFinished) {
return;
}

answered = true;

clearInterval(timerInterval);

const current = questions[currentQuestion];

const buttons =
answersContainer.querySelectorAll("button");

lockAnswers();

// La bonne réponse devient VERT FONCÉ ET VIF.

buttons[current.correct].classList.add("correct");

if (timedOut) {

feedback.textContent =
`⏰ Temps écoulé ! La bonne réponse était : ${current.answers[current.correct]}.`;

feedback.classList.add("error");

} else if (selectedIndex === current.correct) {

score++;

feedback.textContent =
"✓ EXCELLENTE RÉPONSE ! Bravo !";

feedback.classList.add("success");

} else {

// La mauvaise réponse devient ROUGE VIF.

buttons[selectedIndex].classList.add("wrong");

feedback.textContent =
`✗ Mauvaise réponse ! La bonne réponse était : ${current.answers[current.correct]}.`;

feedback.classList.add("error");

}

updateProgressAfterAnswer();

nextQuestionTimeout = setTimeout(() => {

currentQuestion++;

showQuestion();

}, CORRECTION_TIME);

}


// ========================================
// SÉLECTIONNER UNE RÉPONSE
// ========================================

function selectAnswer(selectedIndex) {

showCorrection(selectedIndex);

}


// ========================================
// TEMPS ÉCOULÉ
// ========================================

function handleTimeout() {

showCorrection(null, true);

}


// ========================================
// CALCULER LA NOTE
// ========================================

function calculateGrade(score) {

if (score === 10) return "A+";

if (score === 9) return "A";

if (score === 8) return "A-";

if (score === 7) return "B+";

if (score === 6) return "B";

if (score === 5) return "C+";

if (score === 4) return "C";

if (score === 3) return "D";

if (score === 2) return "E";

if (score === 1) return "F+";

return "F";

}


// ========================================
// APPRÉCIATION
// ========================================

function getGradeMessage(score) {

if (score === 10) {

return "🏆 Exceptionnel ! Tu as répondu correctement à toutes les questions !";

}

if (score >= 8) {

return "🌟 Excellent travail ! Tu possèdes de solides connaissances. Continue ainsi !";

}

if (score >= 6) {

return "👏 Très bien ! Tu progresses. Quelques vidéos supplémentaires pourraient t'aider à atteindre le sommet !";

}

if (score >= 4) {

return "📚 Bon début ! Découvre nos vidéos pour enrichir tes connaissances et améliorer ton score.";

}

if (score >= 1) {

return "💪 Ne te décourage pas ! Chaque erreur est une occasion d'apprendre. Regarde nos vidéos et retente ta chance.";

}

return "🎯 C'est le moment idéal pour apprendre ! Découvre nos vidéos, puis reviens tester tes connaissances.";

}


// ========================================
// AFFICHER LES RÉSULTATS
// ========================================

// ========================================
// ANIMATION DES CONFETTIS
// ========================================

function celebrateResult() {

// Respecter les préférences de réduction des animations.
if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
return;
}

const container = document.createElement("div");
container.className = "confetti-container";
container.setAttribute("aria-hidden", "true");

document.body.appendChild(container);

const colors = [
"#FFD700",
"#FF4757",
"#2ED573",
"#1E90FF",
"#A55EEA",
"#FF8C42"
];

for (let i = 0; i < 120; i++) {

const confetti = document.createElement("span");
confetti.className = "confetti";

confetti.style.left = Math.random() * 100 + "vw";

confetti.style.backgroundColor =
colors[Math.floor(Math.random() * colors.length)];

confetti.style.animationDuration =
(2.5 + Math.random() * 3) + "s";

confetti.style.animationDelay =
Math.random() * 1.5 + "s";

confetti.style.setProperty(
"--drift",
(Math.random() * 240 - 120) + "px"
);

confetti.style.setProperty(
"--rotation",
(Math.random() * 1440 - 720) + "deg"
);

container.appendChild(confetti);
}

setTimeout(() => {
container.remove();
}, 7500);
}


function finishQuiz() {

clearInterval(timerInterval);
clearTimeout(nextQuestionTimeout);

quizFinished = true;

totalElapsedSeconds = Math.min(
TOTAL_QUESTIONS * QUESTION_TIME,
Math.round((Date.now() - quizStartTime) / 1000)
);

questionScreen.hidden = true;
resultScreen.hidden = false;

resultScreen.classList.remove("celebration-active");

// Réinitialiser l'animation
void resultScreen.offsetWidth;

// Activer les animations
resultScreen.classList.add("celebration-active");

resultScore.textContent =
`Ton score : ${score}/${TOTAL_QUESTIONS}`;

const grade = calculateGrade(score);

celebrateResult();

resultGrade.textContent = grade;

resultGrade.classList.remove(
"grade-excellent",
"grade-medium",
"grade-low"
);

if (score >= 8) {

resultGrade.classList.add("grade-excellent");

} else if (score >= 4) {

resultGrade.classList.add("grade-medium");

} else {

resultGrade.classList.add("grade-low");

}

resultTime.textContent =
`⏱️ Temps total : ${formatTime(totalElapsedSeconds)}`;

resultMessage.textContent =
getGradeMessage(score);

progressBar.style.width = "100%";

progressTrack.setAttribute(
"aria-valuenow",
TOTAL_QUESTIONS
);

}


// ========================================
// FORMATER LE TEMPS
// ========================================

function formatTime(seconds) {

const minutes = Math.floor(seconds / 60);

const remainingSeconds = seconds % 60;

return `${minutes} min ${remainingSeconds} s`;

}


// ========================================
// RECOMMENCER LE QUIZ
// ========================================

restartButton.addEventListener("click", startQuiz);


// ========================================
// LANCER LE QUIZ
// ========================================

startQuiz();
